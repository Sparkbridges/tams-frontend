import {
  Document,
  Page,
  Text,
  View,
  StyleSheet,
  pdf,
} from '@react-pdf/renderer'
import type {
  AttendanceReportColumn,
  AttendanceReportRecord,
} from '#/lib/types/api/attendanceReports'
import { reportCell } from '#/lib/utils/helpers/attendanceReports'

const styles = StyleSheet.create({
  page: { padding: 28, fontSize: 8, fontFamily: 'Helvetica' },
  title: { fontSize: 17, marginBottom: 8, color: '#016AEA' },
  metadata: { fontSize: 9, marginBottom: 6 },
  row: { flexDirection: 'row', borderBottomWidth: 0.5, borderColor: '#dddddd' },
  cell: { flex: 1, padding: 5 },
  header: { backgroundColor: '#EFF6FF', fontWeight: 'bold' },
  footer: {
    position: 'absolute',
    bottom: 14,
    left: 28,
    right: 28,
    textAlign: 'right',
    color: '#64748B',
  },
})

export async function generateAttendancePdf({
  title,
  period,
  generatedBy,
  rows,
  columns,
  warnings = [],
}: {
  title: string
  period: string
  generatedBy: string
  rows: AttendanceReportRecord[]
  columns: AttendanceReportColumn[]
  warnings?: string[]
}) {
  return pdf(
    <Document title={title} author={generatedBy}>
      <Page size="A3" orientation="landscape" style={styles.page}>
        <Text style={styles.title}>{title}</Text>
        <Text style={styles.metadata}>Attendance period: {period}</Text>
        <Text style={styles.metadata}>
          Generated by {generatedBy} on {new Date().toLocaleString()}
        </Text>
        {warnings.map((warning) => (
          <Text style={styles.metadata} key={warning}>
            {warning}
          </Text>
        ))}
        <View style={[styles.row, styles.header]} fixed>
          {columns.map((column) => (
            <Text style={styles.cell} key={column.value}>
              {column.label}
            </Text>
          ))}
        </View>
        {rows.map((row, index) => (
          <View style={styles.row} key={index} wrap={false}>
            {columns.map((column) => (
              <Text style={styles.cell} key={column.value}>
                {String(reportCell(row[column.value]))}
              </Text>
            ))}
          </View>
        ))}
        <Text
          style={styles.footer}
          fixed
          render={({ pageNumber, totalPages }) =>
            `Page ${pageNumber} of ${totalPages}`
          }
        />
      </Page>
    </Document>,
  ).toBlob()
}
