import { describe, expect, it } from 'vitest'
import { Children, isValidElement } from 'react'
import type { ReactElement, ReactNode } from 'react'
import { Image, Page, Text, View } from '@react-pdf/renderer'
import {
  AttendancePdfDocument,
  generateAttendancePdf,
} from './AttendanceReport'

type PdfNodeProps = {
  children?: ReactNode
  fixed?: boolean
  wrap?: boolean
  src?: string
  orientation?: string
  size?: string
  render?: (props: { pageNumber: number; totalPages: number }) => string
}

function elements(node: ReactNode): ReactElement<PdfNodeProps>[] {
  return Children.toArray(node).flatMap((child) =>
    isValidElement<PdfNodeProps>(child)
      ? [child, ...elements(child.props.children)]
      : [],
  )
}

function text(node: ReactNode): string {
  return Children.toArray(node)
    .map((child) =>
      isValidElement<PdfNodeProps>(child)
        ? text(child.props.children)
        : String(child),
    )
    .join(' ')
}

describe('attendance report PDF', () => {
  it('reuses the branded layout for performance without attendance labels', () => {
    const document = AttendancePdfDocument({
      reportCategory: 'Performance',
      title: 'Appraisal Scorecard Report',
      period: '2026',
      generatedBy: 'Ada Admin',
      columns: [{ value: 'name', label: 'Employee' }],
      rows: [{ name: 'Ada' }],
    })
    const content = text(document).replace(/\s+/g, ' ')
    expect(content).toContain('OFFICIAL / PERFORMANCE')
    expect(content).toContain('Appraisal Year 2026')
    expect(content).not.toContain('Attendance')
  })
  it('creates a PDF with attendance-specific metadata and scalar report records', async () => {
    const blob = await generateAttendancePdf({
      title: 'Attendance Summary',
      period: '2026-11-01 to 2026-11-30',
      generatedBy: 'Test Administrator',
      warnings: [
        {
          code: 'active_employees_only',
          message: 'Historical scope uses current employee records.',
        },
        {
          code: 'source_values_passthrough',
          message: 'Source calculation limitation.',
        },
      ],
      columns: [
        { value: 'name', label: 'Employee' },
        { value: 'hours_worked', label: 'Hours worked' },
      ],
      rows: [{ name: 'Ada', hours_worked: '126:30:00' }],
    })
    expect(blob.type).toBe('application/pdf')
    expect(blob.size).toBeGreaterThan(100)
  })

  it('uses company branding, metadata cards and accurate record counts without audit or sync claims', () => {
    const document = AttendancePdfDocument({
      title: 'Attendance Summary',
      period: '2026-11-01 to 2026-11-30',
      generatedBy: 'Ada Admin',
      generatedAt: new Date(2026, 10, 9, 13, 30),
      company: { legal_name: 'Example Company', company_logo: '/logo.png' },
      scope: 'department: 5 / Branches: 2',
      grouping: 'employee',
      columns: [{ value: 'name', label: 'Employee' }],
      rows: [{ name: 'Ada' }, { name: 'Ada' }],
      warnings: [{ code: 'source', message: 'Source calculation limitation.' }],
    })
    const content = text(document).replace(/\s+/g, ' ')
    for (const expected of [
      'Example Company',
      'OFFICIAL / ATTENDANCE',
      '09/11/2026 / 13:30',
      'Scope of Data',
      'department: 5 / Branches: 2',
      'Generated By',
      'Ada Admin',
      'Attendance Period',
      '2026-11-01 to 2026-11-30',
      'Exported Records 2',
      'Report Columns 1',
      'Grouping Employee',
      'Report Warnings and Limitations',
      'Source calculation limitation.',
      'Confidential',
    ]) {
      expect(content).toContain(expected)
    }
    expect(content).not.toMatch(/AUDIT|VERIFIED|ADMS|Synchronized|2 Employees/)
    const nodes = elements(document)
    expect(nodes.find((node) => node.type === Image)?.props.src).toBe(
      '/logo.png',
    )
    expect(nodes.find((node) => node.type === Page)?.props).toMatchObject({
      size: 'A3',
      orientation: 'landscape',
      wrap: true,
    })
  })

  it('keeps every selected cell, preserves zero and missing values, and repeats the table header and footer', () => {
    const document = AttendancePdfDocument({
      title: 'Simple Attendance',
      period: '2026-11-01 to 2026-11-30',
      generatedBy: 'Ada Admin',
      columns: [
        { value: 'name', label: 'Employee' },
        { value: 'late', label: 'Late' },
        { value: 'clockout', label: 'Clock out' },
      ],
      rows: [
        { name: 'Ada', late: 0, clockout: null },
        { name: 'Ben', late: false },
      ],
    })
    const nodes = elements(document)
    const rows = nodes.filter(
      (node) => node.type === View && node.props.wrap === false,
    )
    expect(rows).toHaveLength(2)
    for (const row of rows) {
      expect(
        elements(row.props.children).filter((node) => node.type === Text),
      ).toHaveLength(3)
    }
    expect(text(rows[0])).toBe('Ada 0 Not available')
    expect(text(rows[1])).toBe('Ben No Not available')
    const fixedViews = nodes.filter(
      (node) => node.type === View && node.props.fixed,
    )
    expect(fixedViews).toHaveLength(2)
    expect(text(fixedViews[0])).toBe('Employee Late Clock out')
    expect(text(document)).not.toContain('Report Warnings and Limitations')
    expect(nodes.some((node) => node.type === Image)).toBe(false)
    const footer = nodes.find((node) => node.type === Text && node.props.render)
    expect(footer?.props.render?.({ pageNumber: 2, totalPages: 3 })).toBe(
      'Page 2 of 3',
    )
  })

  it('generates a multipage PDF for a long attendance report', async () => {
    const blob = await generateAttendancePdf({
      title: 'Simple Attendance',
      period: '2026-11-01 to 2026-11-30',
      generatedBy: 'Ada Admin',
      columns: [
        { value: 'name', label: 'Employee' },
        { value: 'hours', label: 'Hours' },
      ],
      rows: Array.from({ length: 120 }, (_, index) => ({
        name: `Employee ${index}`,
        hours: '126:30:00',
      })),
    })
    const bytes = await blob.arrayBuffer()
    const source = new TextDecoder().decode(bytes)
    expect(source.match(/\/Type \/Page\b/g)?.length).toBeGreaterThan(1)
  })
})
